#!/usr/bin/env node
/* thumbs.js — small, local copies of every work's image, so the wall does not
 * pull ~2.6 MB originals from someone else's CDN for a 190-pixel tile.
 *
 * For each work in site/data/portrait.json it writes site/thumbs/<dropId>.webp
 * (600px wide, aspect kept; animated gifs keep their first frame) and the manifest
 * site/data/thumbs.js:  window.THUMBS = { dropId: [width, height], … }
 * The pages use a thumb only if it is in the manifest, so a failed download just
 * means that one tile falls back to the original — never a broken wall.
 *
 * Existing thumbs are kept (a drop's image never changes), so a normal run only
 * fetches what is new. Thumbs for works that left the wall are deleted.
 *
 * Usage:  node producer/thumbs.js [--force]      (needs: npm install --prefix producer)
 */
"use strict";
const fs = require("fs");
const path = require("path");
const sharp = require("sharp");

const SITE = path.join(__dirname, "..", "site");
const PORTRAIT = path.join(SITE, "data", "portrait.json");
const OUT_DIR = path.join(SITE, "thumbs");
const OUT_MANIFEST = path.join(SITE, "data", "thumbs.js");
const WIDTH = 600;
const QUALITY = 72;
const GAP_MS = 100;
const RETRIES = 3;
const force = process.argv.includes("--force");
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function download(url) {
  for (let attempt = 1; attempt <= RETRIES; attempt++) {
    try {
      const res = await fetch(url);
      if (!res.ok) throw new Error("HTTP " + res.status);
      return Buffer.from(await res.arrayBuffer());
    } catch (err) {
      if (attempt === RETRIES) throw err;
      await sleep(500 * attempt);
    }
  }
}

(async () => {
  const works = JSON.parse(fs.readFileSync(PORTRAIT, "utf8")).works;
  fs.mkdirSync(OUT_DIR, { recursive: true });

  const manifest = {};
  let made = 0, kept = 0, failed = 0;
  for (const w of works) {
    const file = path.join(OUT_DIR, w.drop + ".webp");
    try {
      if (force || !fs.existsSync(file)) {
        const src = await download(w.img);
        await sharp(src).rotate().resize({ width: WIDTH, withoutEnlargement: true })
          .webp({ quality: QUALITY }).toFile(file);
        made++;
        await sleep(GAP_MS);
      } else kept++;
      const m = await sharp(file).metadata();
      manifest[w.drop] = [m.width, m.height];
    } catch (err) {
      failed++;
      console.error(`[thumbs] ${w.drop}: ${err.message} — tile will use the original`);
    }
  }

  // sweep thumbs whose work is no longer on the wall
  const live = new Set(works.map((w) => w.drop + ".webp"));
  let swept = 0;
  for (const f of fs.readdirSync(OUT_DIR)) if (f.endsWith(".webp") && !live.has(f)) { fs.unlinkSync(path.join(OUT_DIR, f)); swept++; }

  fs.writeFileSync(OUT_MANIFEST,
    "/* dropId -> [w,h] of site/thumbs/<dropId>.webp · regenerated by producer/thumbs.js */\n" +
    "window.THUMBS=" + JSON.stringify(manifest) + ";\n");
  console.error(`[thumbs] ${Object.keys(manifest).length}/${works.length} thumbs · ${made} new · ${kept} kept · ${swept} swept · ${failed} failed`);
})().catch((e) => { console.error("[thumbs] FAILED:", e.stack || e.message); process.exit(1); });
